#!/usr/bin/env python3
"""Aggregate sizes.py output into RESULTS.md tables.  usage: aggregate.py OUTDIR ARCHIVE > RESULTS.md"""
import sys, os, json, glob, re, collections
from urllib.parse import urlparse

outdir, archive = sys.argv[1], sys.argv[2]
rows = []
raw_order = collections.defaultdict(list)
for p in sorted(glob.glob(os.path.join(outdir, '*__*.jsonl'))):
    run, raw = os.path.basename(p)[:-6].split('__')
    raw_order[run].append(raw)
    for l in open(p):
        rows.append(json.loads(l))

HOSTS = {'chatgpt.com': 'openai'}


def prov(r):
    h = urlparse(r['url']).hostname or '?'
    if 'chatgpt' in h or 'openai' in h:
        return 'openai'
    if 'mimo' in h or 'xiaomi' in h:
        return 'mimotp'
    if 'paper' in h:
        return 'paper'
    return h


hosts = collections.Counter(urlparse(r['url']).hostname for r in rows)


def pct(v, q):
    v = sorted(v)
    if not v:
        return None
    k = max(1, -(-len(v) * q // 100))  # nearest rank
    return v[int(k) - 1]


def kb(x):
    return '-' if x is None else f'{x/1024:.1f}'


def fmt(x):
    return '-' if x is None else f'{x:,}'


for r in rows:
    r['prov'] = prov(r)
    r['mkey'] = f"{r['prov']} {r.get('model')}"

P = print
P('# Provider request sizes, 2026-10-17 C++26 campaign')
P()
P('Read-only measurement of every site-1301 provider request (exact wire body) in every raw run under')
P(f'`{archive}`. Generated by `sizes.py` + `aggregate.py` in this directory.')
P('Sizes are in KiB (1024 bytes) unless marked. Percentiles are nearest-rank. "input" is the exact byte span of the')
P('top-level `"input"` JSON value in the wire body (brackets included); "tools" and "instructions" likewise.')
P('Tokens are the provider-reported `usage.input_tokens` parsed from that request\'s response stream (when it completed).')
P()
P(f'Requests: {len(rows)}; runs: {len(raw_order)}; raw runs: {sum(len(v) for v in raw_order.values())}.')
P(f'URL hosts: {dict(hosts)}.')
und = [r for r in rows if not r.get('decoded')]
P(f'Undecodable wire bodies: {len(und)}.')
for r in und:
    P(f'- {r["run"]}/{r["raw"]} ord {r["req_ord"]}: {r.get("decode_error")}')
P()

# 1. per model
P('## 1. Per provider/model')
P()
P('| provider model | effort(s) | requests | wire median | p90 | p99 | max | input median | p90 | p99 | max | input items median | p90 | max | input tokens median | p90 | p99 | max | wire bytes/input token (median) |')
P('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
by = collections.defaultdict(list)
for r in rows:
    by[r['mkey']].append(r)
for k in sorted(by):
    g = by[k]
    w = [r['body_bytes'] for r in g]
    ib = [r['input_bytes'] for r in g if r.get('input_bytes') is not None]
    it = [r['input_items'] for r in g if r.get('input_items') is not None]
    tk = [r['usage_input_tokens'] for r in g if r.get('usage_input_tokens')]
    ratio = [r['body_bytes'] / r['usage_input_tokens'] for r in g if r.get('usage_input_tokens')]
    eff = ','.join(sorted({str(r.get('effort')) for r in g}))
    P(f'| {k} | {eff} | {len(g)} | ' + ' | '.join(kb(pct(w, q)) for q in (50, 90, 99, 100)) + ' | '
      + ' | '.join(kb(pct(ib, q)) for q in (50, 90, 99, 100)) + ' | '
      + ' | '.join(fmt(pct(it, q)) for q in (50, 90, 100)) + ' | '
      + ' | '.join(fmt(pct(tk, q)) for q in (50, 90, 99, 100)) + ' | '
      + (f'{pct(ratio, 50):.2f}' if ratio else '-') + ' |')
P()
P('Fixed overhead per request (constant across a model\'s requests unless noted):')
P()
P('| provider model | tools KiB (min-max) | n tools (min-max) | instructions KiB (min-max) | wire minus input KiB median |')
P('|---|---|---|---|---|')
for k in sorted(by):
    g = [r for r in by[k] if r.get('decoded')]
    tb = [r['tools_bytes'] for r in g if r.get('tools_bytes') is not None]
    nt = [r['n_tools'] for r in g if r.get('n_tools') is not None]
    ins = [r['instructions_bytes'] for r in g if r.get('instructions_bytes') is not None]
    ov = [r['body_bytes'] - r['input_bytes'] for r in g if r.get('input_bytes') is not None]
    P(f'| {k} | {kb(min(tb)) if tb else "-"}-{kb(max(tb)) if tb else "-"} | {min(nt) if nt else "-"}-{max(nt) if nt else "-"} | '
      f'{kb(min(ins)) if ins else "-"}-{kb(max(ins)) if ins else "-"} | {kb(pct(ov, 50))} |')
P()

# 2. per run
P('## 2. Per run (requests in begin-clock order)')
P()
P('Order is the `provider.transport` region begin clock (CLOCK_MONOTONIC), falling back to raw-run then record order.')
P('"middle" is request index floor(n/2) (0-based). Wire KiB / input KiB / input items / input tokens.')
P('"native" columns are Blackbird\'s own `[request N native request bytes]` lines from the run\'s stdout logs')
P('(one per logical request, BBM2 packet size; not joined one-to-one to wire attempts).')
P()
P('| run | model | requests | max wire | max input | max items | max tokens | first wire / input / items / tok | middle | last | native n | native first | native max | native last |')
P('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
byrun = collections.defaultdict(list)
for r in rows:
    byrun[r['run']].append(r)
NAT = re.compile(r'\[request (\d+) native request bytes\]')


def native(run):
    vals = []
    logs = sorted(glob.glob(os.path.join(archive, run, 'stdout.*.log')), key=lambda p: int(p.split('.')[-2]))
    for p in logs:
        with open(p, errors='replace') as f:
            vals += [int(m.group(1)) for m in NAT.finditer(f.read())]
    return vals


def cell(r):
    return f"{kb(r['body_bytes'])} / {kb(r.get('input_bytes'))} / {fmt(r.get('input_items'))} / {fmt(r.get('usage_input_tokens'))}"


growth = {}
for run in sorted(byrun):
    g = byrun[run]
    ro = {raw: i for i, raw in enumerate(raw_order[run])}
    g.sort(key=lambda r: (r['t_begin'] if r.get('t_begin') is not None else float('inf'), ro[r['raw']], r['req_ord']))
    n = len(g)
    mx = max(g, key=lambda r: r['body_bytes'])
    models = ','.join(sorted({str(r.get('model')) for r in g}))
    nat = native(run)
    ib = [r.get('input_bytes') or 0 for r in g]
    it = [r.get('input_items') or 0 for r in g]
    tk = [r.get('usage_input_tokens') or 0 for r in g]
    growth[run] = g
    P(f"| {run} | {models} | {n} | {kb(mx['body_bytes'])} | {kb(max(ib))} | {max(it)} | {fmt(max(tk))} | {cell(g[0])} | {cell(g[n//2])} | {cell(g[-1])} | "
      f"{len(nat)} | {kb(nat[0]) if nat else '-'} | {kb(max(nat)) if nat else '-'} | {kb(nat[-1]) if nat else '-'} |")
P()
# growth per request
P('Average growth per request (last minus first wire bytes, divided by requests-1), and whether the wire size ever')
P('shrank by more than 10% between consecutive requests (a reset, compaction or new conversation):')
P()
P('| run | requests | KiB/request | shrink events (>10%) |')
P('|---|---|---|---|')
for run, g in sorted(growth.items()):
    n = len(g)
    per = (g[-1]['body_bytes'] - g[0]['body_bytes']) / (n - 1) if n > 1 else 0
    shr = sum(1 for a, b in zip(g, g[1:]) if b['body_bytes'] < 0.9 * a['body_bytes'])
    P(f'| {run} | {n} | {per/1024:.1f} | {shr} |')
P()

# 3. top 10
P('## 3. Largest 10 requests by wire bytes')
P()
P('| # | run/raw | req ord | provider model | effort | wire bytes | input bytes | input items | tools bytes | input tokens (cached) | HTTP | largest input item bytes (approx) |')
P('|---|---|---|---|---|---|---|---|---|---|---|---|')
for i, r in enumerate(sorted(rows, key=lambda r: -r['body_bytes'])[:10], 1):
    P(f"| {i} | {r['run']}/{r['raw']} | {r['req_ord']} | {r['mkey']} | {r.get('effort')} | {fmt(r['body_bytes'])} | {fmt(r.get('input_bytes'))} | "
      f"{fmt(r.get('input_items'))} | {fmt(r.get('tools_bytes'))} | {fmt(r.get('usage_input_tokens'))} ({fmt(r.get('usage_cached_tokens'))}) | {r.get('http')} | {fmt(r.get('max_item_bytes_approx'))} |")
P()
P('Largest 10 by provider-reported input tokens:')
P()
P('| # | run | provider model | wire bytes | input bytes | input tokens | cached | bytes/token |')
P('|---|---|---|---|---|---|---|---|')
for i, r in enumerate(sorted([r for r in rows if r.get('usage_input_tokens')], key=lambda r: -r['usage_input_tokens'])[:10], 1):
    P(f"| {i} | {r['run']} | {r['mkey']} | {fmt(r['body_bytes'])} | {fmt(r.get('input_bytes'))} | {fmt(r['usage_input_tokens'])} | {fmt(r.get('usage_cached_tokens'))} | {r['body_bytes']/r['usage_input_tokens']:.2f} |")
P()

# 4. refusals
P('## 4. HTTP status and refusals')
P()
st = collections.Counter((r['mkey'], r.get('http'), r.get('term_code'), r.get('term_detail')) for r in rows)
P('| provider model | HTTP (1302) | terminal ErrorCode | detail | count |')
P('|---|---|---|---|---|')
for (k, h, c, d), n in sorted(st.items(), key=lambda x: str(x)):
    P(f'| {k} | {h} | {c} | {d} | {n} |')
P()
P('Response bodies of every non-200 request and every stream with an error/failed/incomplete marker:')
P()
seen = collections.Counter()
for r in rows:
    if r.get('http') not in (200, None) or r.get('refuse_hits'):
        sig = (r['mkey'], r.get('http'), (r.get('resp_head') or '')[:300])
        seen[sig] += 1
        if seen[sig] > 1:
            continue
        P(f"- {r['run']}/{r['raw']} ord {r['req_ord']} {r['mkey']} HTTP {r.get('http')} wire {fmt(r['body_bytes'])} B, "
          f"markers {r.get('refuse_hits')}, response bytes {r.get('resp_bytes')}:")
        P('  ```')
        P('  ' + (r.get('resp_head') or '')[:800].replace('\n', '\n  '))
        P('  ```')
dups = {k: v for k, v in seen.items() if v > 1}
for k, v in dups.items():
    P(f'- (the body above for {k[0]} HTTP {k[1]} repeated in {v} requests in total)')
for k, v in seen.items():
    pass
P()
P('Requests with no HTTP status record (timeouts at 180 s or missing 1302): ' +
  str(sum(1 for r in rows if r.get('http') is None)))
